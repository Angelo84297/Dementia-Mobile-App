from sqlmodel import Field, SQLModel, UniqueConstraint
from datetime import datetime, timezone
from typing import List

class User(SQLModel, table=True):  # table=True tells SQLModel this represents a table. It is registered in the metadata object
    __tablename__ = "users"   # table name replaced with users
    user_id: int | None = Field(default=None, primary_key=True)  # Null allowed as id is generated by the database once the object is stored
    first_name: str
    last_name: str
    email: str | None = None # allowed to be null and set to null by default
    role: str # Patient / Caregiver
    address: str | None = None

class Patient(SQLModel, table=True): 
    patient_id: int | None = Field(default=None, primary_key=True)
    user_id: int = Field(foreign_key="users.user_id")
    age: int | None = None

class HealthRecord(SQLModel, table=True):    # See scripts in database folder to find table changes
    record_id: int | None = Field(default=None, primary_key=True)
    patient_id: int = Field(foreign_key="patient.patient_id")
    # sets timestamp automatically depending on timezone every time a new health record is logged
    hour_block: datetime = Field(default_factory=lambda: datetime.now(timezone.utc)) 
    step_count: int 
    average_heart_rate: int | None = None

    __table_args__ = (
        UniqueConstraint("patient_id", "hour_block"),  
    )

class Mood(SQLModel, table=True): 
    mood_id: int | None = Field(default=None, primary_key=True) 
    patient_id: int = Field(foreign_key="patient.patient_id")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc)) 
    mood: str   # changed to int 

class Sleep(SQLModel, table=True): 
    sleep_id: int | None = Field(default=None, primary_key=True) 
    patient_id: int = Field(foreign_key="patient.patient_id")
    start_time: datetime 
    end_time: datetime
    minutes_asleep: int
    minutes_awake: int 

    __table_args__ = (
        UniqueConstraint("patient_id", "end_time"),  # create unique key allowing new fetches to update existing values
    )

"""
Defines the JSON body the client sends to store a mood record. 
"""
class MoodInput(SQLModel):
    patient_id : int 
    mood: int 

class MoodRead(SQLModel):  # what the UI needs to display
    mood: int
    created_at: datetime

class DailyHealthRecord(SQLModel): 
    total_step_count : int
    average_heart_rate : int | None = None   # set to null automatically if no value is returned
    max_sleep_minutes : int | None = None

class WellbeingAdvice(SQLModel):
    advice : str 

class SleepSession(SQLModel): 
    start_time : datetime
    end_time : datetime
    min_awake : int
    min_asleep : int 

class HourlyActivity(SQLModel): 
    hour_block:  datetime
    avg_heart_rate : int | None
    step_count : int 

class GeminiPayload(SQLModel): 
    hourly_activity: List[HourlyActivity] = []  # assign empty list if no data is found
    sleep_sessions: List[SleepSession] = []

