"""
Data model classes
"""
from sqlmodel import Column, Field, SQLModel, Text, UniqueConstraint
from datetime import datetime, timezone
from typing import List

class Users(SQLModel, table=True):  
    user_id: int | None = Field(default=None, primary_key=True)  # Null allowed as id is generated by the database
    first_name: str
    last_name: str
    email: str | None = None 
    role: str # Patient / Caregiver
    address: str | None = None


class Patient(SQLModel, table=True): 
    patient_id: int | None = Field(default=None, primary_key=True)
    user_id: int = Field(foreign_key="users.user_id")
    age: int | None = None

class HealthRecord(SQLModel, table=True):   
    record_id: int | None = Field(default=None, primary_key=True)
    patient_id: int = Field(foreign_key="patient.patient_id")
    hour_block: datetime = Field(default_factory=lambda: datetime.now(timezone.utc)) # the database does not store the tz info
    step_count: int   # for simplicity 0 is assigned in absence of data 
    average_heart_rate: int | None = None
    __table_args__ = (
        UniqueConstraint("patient_id", "hour_block"),  # avoids data duplication
    )

class Mood(SQLModel, table=True): 
    mood_id: int | None = Field(default=None, primary_key=True) 
    patient_id: int = Field(foreign_key="patient.patient_id")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc)) 
    mood: int  

class Sleep(SQLModel, table=True): 
    sleep_id: int | None = Field(default=None, primary_key=True) 
    patient_id: int = Field(foreign_key="patient.patient_id")
    start_time: datetime 
    end_time: datetime
    minutes_asleep: int
    minutes_awake: int 

    __table_args__ = (
        UniqueConstraint("patient_id", "start_time"),  # start_time was picked since stable. end_time may be updated by Google Health. 
    )

class WellbeingAdvice(SQLModel, table=True):
    advice_id: int | None = Field(default=None, primary_key=True) 
    patient_id: int = Field(foreign_key="patient.patient_id")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))  # utc information is lost in db
    content: str = Field(sa_column=Column(Text))  # Text is used as the Gemini response is long.  

class Task(SQLModel, table=True): 
    task_id : int | None = Field(default=None, primary_key=True)
    patient_id: int = Field(foreign_key="patient.patient_id")
    description: str 
    notes : str | None = None   # currently not implemented
    notification_time: datetime
    frequency : str 
    status : str | None = None  # currently not implemented
    weekday : int | None = None    # needed for weekly frequency. 1 represents Sunday and 7 represents Saturday.

class TaskRead(SQLModel):   # doesn't include patient_id as the FE doesn't need it
    task_id : int 
    description: str  
    notification_time: datetime
    frequency : str | None 
    weekday : int | None

class TaskInput(SQLModel): 
    patient_id: int = Field(foreign_key="patient.patient_id")
    description: str    
    notification_time: datetime # format sent by the front end
    frequency : str  
    weekday: int | None  # for when frequency is set on daily

"""
Defines the JSON body the client sends to store a mood record. 
"""
class MoodInput(SQLModel):
    patient_id : int 
    mood: int 

class MoodRead(SQLModel):  
    mood_id : int
    mood: int
    created_at: datetime

class DailyHealthRecordRead(SQLModel): 
    total_step_count : int | None  # Null is returned when it's stored as 0, as it's more accurate
    average_heart_rate : int | None 
    max_sleep_minutes : int | None 

class WellbeingAdviceRead(SQLModel):
    content : str 
    created_at : datetime   

class SleepSession(SQLModel): 
    start_time : datetime
    end_time : datetime
    min_awake : int
    min_asleep : int 

class HourlyActivity(SQLModel): 
    hour_block:  datetime
    avg_heart_rate : int | None
    step_count : int 

class GeminiPayload(SQLModel): 
    hourly_activity: List[HourlyActivity] 
    sleep_sessions: List[SleepSession] 
    mood_list: List[MoodRead] 

