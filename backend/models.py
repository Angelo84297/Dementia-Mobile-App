from sqlmodel import Field, SQLModel
from datetime import datetime, timezone


class User(SQLModel, table=True):  # table=True tells SQLModel this represents a table. It is registered in the metadata object
    user_id: int | None = Field(default=None, primary_key=True)  # Null allowed as id is generated by the database once the object is stored
    first_name: str
    last_name: str
    email: str | None = None # allowed to be null and set to null by default
    role: str # Patient / Caregiver
    address: str | None = None

class Patient(SQLModel, table=True): 
    patient_id: int | None = Field(default=None, primary_key=True)
    user_id: int = Field(foreign_key="user.user_id")
    age: int 

class HealthRecord(SQLModel, table=True): 
    record_id: int | None = Field(default=None, primary_key=True)
    patient_id: int = Field(foreign_key="patient.patient_id")
    # sets timestamp automatically depending on timezone every time a new health record is logged
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc)) 
    step_count: int 
    sleep_hours: float  # to decide whether most of these are allowed to be null
